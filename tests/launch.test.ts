import { afterAll, describe, expect, test } from "bun:test";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { nodeRuntime, resolveLaunch } from "../src/launch.js";
import { STUB_BIN } from "./helpers.js";

const dirs: string[] = [];
function tempDir(): string {
	const dir = mkdtempSync(path.join(tmpdir(), "picc-launch-"));
	dirs.push(dir);
	return dir;
}
afterAll(() => {
	for (const dir of dirs.splice(0)) rmSync(dir, { recursive: true, force: true });
});

/** npm's cmd-shim layout for `cmdc` (the last line is what the resolver must read). */
function npmShim(script = "node_modules\\command-code\\dist\\cli.mjs"): string {
	return [
		"@ECHO off",
		"GOTO start",
		":find_dp0",
		"SET dp0=%~dp0",
		"EXIT /b",
		":start",
		"SETLOCAL",
		"CALL :find_dp0",
		"",
		'IF EXIST "%dp0%\\node.exe" (',
		'  SET "_prog=%dp0%\\node.exe"',
		") ELSE (",
		'  SET "_prog=node"',
		"  SET PATHEXT=%PATHEXT:;.JS;=;%",
		")",
		"",
		`endLocal & goto #_undefined_# 2>NUL || title %COMSPEC% & "%_prog%"  "%dp0%\\${script}" %*`,
		"",
	].join("\r\n");
}

/** Compare paths regardless of the separator the resolver used. */
function samePath(actual: string, expected: string): boolean {
	return actual.replace(/\\/g, "/") === expected.replace(/\\/g, "/");
}

describe("resolveLaunch on win32", () => {
	test("an npm-style cmdc.cmd on PATH resolves to its Node entry script", () => {
		const dir = tempDir();
		writeFileSync(path.join(dir, "cmdc.cmd"), npmShim());
		const env: NodeJS.ProcessEnv = { PATH: dir };

		const launch = resolveLaunch("cmdc", env, "win32");

		expect(launch.command).toBe(nodeRuntime(env));
		expect(launch.args).toHaveLength(1);
		expect(samePath(launch.args[0]!, path.join(dir, "node_modules", "command-code", "dist", "cli.mjs"))).toBe(true);
	});

	// Last line of a shim generated by npm's own cmd-shim for command-code (dist/index.mjs).
	test("the current npm cmd-shim line with the PATHEXT reset resolves too", () => {
		const dir = tempDir();
		writeFileSync(
			path.join(dir, "cmdc.cmd"),
			'@ECHO off\r\nGOTO start\r\n:find_dp0\r\nSET dp0=%~dp0\r\nEXIT /b\r\n:start\r\nSETLOCAL\r\nCALL :find_dp0\r\n\r\nIF EXIST "%dp0%\\node.exe" (\r\n  SET "_prog=%dp0%\\node.exe"\r\n) ELSE (\r\n  SET "_prog=node"\r\n  SET PATHEXT=%PATHEXT:;.JS;=;%\r\n)\r\n\r\nendLocal & goto #_undefined_# 2>NUL || title %COMSPEC% & set PATHEXT=%PATHEXT:;.JS;=;% & "%_prog%"  "%dp0%\\node_modules\\command-code\\dist\\index.mjs" %*\r\n',
		);
		// A bare `cmdc` sh shim sits next to it, as npm writes all three.
		writeFileSync(path.join(dir, "cmdc"), "#!/bin/sh\nexec node \"$basedir/node_modules/command-code/dist/index.mjs\" \"$@\"\n");
		const env: NodeJS.ProcessEnv = { PATH: undefined, Path: dir };

		const launch = resolveLaunch("cmdc", env, "win32");

		expect(launch.command).toBe(nodeRuntime(env));
		expect(samePath(launch.args[0]!, path.join(dir, "node_modules", "command-code", "dist", "index.mjs"))).toBe(true);
	});

	test("a node.exe next to the shim is preferred over the runtime", () => {
		const dir = tempDir();
		writeFileSync(path.join(dir, "cmdc.cmd"), npmShim());
		writeFileSync(path.join(dir, "node.exe"), "");

		const launch = resolveLaunch("cmdc", { PATH: dir }, "win32");

		expect(launch.command).toBe(path.join(dir, "node.exe"));
		expect(samePath(launch.args[0]!, path.join(dir, "node_modules", "command-code", "dist", "cli.mjs"))).toBe(true);
	});

	test("a .bat shim is parsed the same way", () => {
		const dir = tempDir();
		writeFileSync(path.join(dir, "cmdc.bat"), npmShim());

		const launch = resolveLaunch("cmdc", { PATH: dir }, "win32");

		expect(launch.command).toBe(nodeRuntime({}));
		expect(launch.args).toHaveLength(1);
	});

	test("an .exe on PATH is returned directly, and PATH may be spelled Path", () => {
		const dir = tempDir();
		const exe = path.join(dir, "cmdc.exe");
		writeFileSync(exe, "");

		expect(resolveLaunch("cmdc", { Path: dir }, "win32")).toEqual({ command: exe, args: [] });
	});

	test("an older shim using %~dp0 without a trailing percent is parsed too", () => {
		const dir = tempDir();
		writeFileSync(
			path.join(dir, "cmdc.cmd"),
			[
				"@ECHO off",
				'IF EXIST "%~dp0\\node.exe" (',
				'  "%~dp0\\node.exe"  "%~dp0\\..\\command-code\\dist\\cli.mjs" %*',
				") ELSE (",
				"  SETLOCAL",
				"  SET PATHEXT=%PATHEXT:;.JS;=;%",
				'  node  "%~dp0\\..\\command-code\\dist\\cli.mjs" %*',
				")",
				"",
			].join("\r\n"),
		);

		const launch = resolveLaunch("cmdc", { PATH: dir }, "win32");

		expect(launch.command).toBe(nodeRuntime({}));
		expect(
			samePath(launch.args[0]!, path.join(dir, "..", "command-code", "dist", "cli.mjs")),
		).toBe(true);
	});

	test("an unparseable .cmd throws the no-shell guidance", () => {
		const dir = tempDir();
		writeFileSync(path.join(dir, "cmdc.cmd"), "@ECHO off\r\nnode -e \"console.log(1)\"\r\n");

		expect(() => resolveLaunch("cmdc", { PATH: dir }, "win32")).toThrow(
			/cannot launch .*cmdc\.cmd without a shell; set CMDCODE_BRIDGE_BIN/,
		);
	});

	test("CMDCODE_BRIDGE_BIN set to a .cmd path is parsed too", () => {
		const dir = tempDir();
		const shim = path.join(dir, "cmdc.cmd");
		writeFileSync(shim, npmShim());

		const launch = resolveLaunch(shim, {}, "win32");

		expect(launch.command).toBe(nodeRuntime({}));
		expect(samePath(launch.args[0]!, path.join(dir, "node_modules", "command-code", "dist", "cli.mjs"))).toBe(true);
	});

	test("a shebang script found by bare name on PATH runs through Node", () => {
		const dir = tempDir();
		const script = path.join(dir, "cmdc");
		writeFileSync(script, "#!/usr/bin/env node\nconsole.log(1);\n");

		const launch = resolveLaunch("cmdc", { PATH: dir }, "win32");

		expect(launch).toEqual({ command: nodeRuntime({}), args: [script] });
	});
});

describe("resolveLaunch for Node entry scripts", () => {
	test("a shebang script path runs through the Node runtime", () => {
		const dir = tempDir();
		const script = path.join(dir, "cli");
		writeFileSync(script, "#!/usr/bin/env node\nconsole.log(1);\n");

		expect(resolveLaunch(script, {}, "darwin")).toEqual({ command: nodeRuntime({}), args: [script] });
	});

	test(".mjs, .js and .cjs paths run through the Node runtime", () => {
		const dir = tempDir();
		for (const name of ["cli.mjs", "cli.js", "cli.cjs"]) {
			const file = path.join(dir, name);
			writeFileSync(file, "export {};\n");
			expect(resolveLaunch(file, {}, "win32")).toEqual({ command: nodeRuntime({}), args: [file] });
		}
	});

	test("the test stub resolves the same way on Windows", () => {
		expect(resolveLaunch(STUB_BIN, {}, "win32")).toEqual({ command: nodeRuntime({}), args: [STUB_BIN] });
	});
});

describe("resolveLaunch elsewhere", () => {
	test("the default `cmd` and absolute binaries pass through unchanged", () => {
		expect(resolveLaunch("cmd", {}, "darwin")).toEqual({ command: "cmd", args: [] });
		expect(resolveLaunch("cmd", {}, "linux")).toEqual({ command: "cmd", args: [] });
		expect(resolveLaunch("/opt/commandcode/cmd", {}, "linux")).toEqual({ command: "/opt/commandcode/cmd", args: [] });
	});

	test("an unknown win32 name stays as is so the spawn error is reported by the caller", () => {
		const dir = tempDir();
		expect(resolveLaunch("cmdc", { PATH: dir }, "win32")).toEqual({ command: "cmdc", args: [] });
	});
});
