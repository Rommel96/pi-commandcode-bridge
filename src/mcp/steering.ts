/**
 * Delegation steering for `cmd` runs that expose Pi subagents (issue #1).
 *
 * `cmd` always registers its own built-in `agent` tool. When both that tool and
 * Pi's `subagent_run` are available, the model tends to pick the native one,
 * which runs the subagent inside `cmd` and is invisible to the Pi host. A small
 * cmd mod can block the native tool deterministically and hand the model the
 * MCP tool name to use instead.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";

export const STEERING_MOD_FILE = "pi-delegation-guard.ts";

/** The exact MCP tool name the model should call instead of the native `agent`. */
export function subagentToolName(serverName: string): string {
	return `mcp__${serverName}__subagent_run`;
}

/**
 * Write the guard mod into the broker's private temp directory and return its
 * absolute path. It is plain TypeScript with no imports so `cmd`'s jiti loader
 * can evaluate it without resolving any package.
 */
export function writeSteeringMod(dir: string, serverName: string): string {
	const tool = subagentToolName(serverName);
	const source = `// Generated by pi-commandcode-bridge for this run.
export default function (cmd) {
	cmd.hooks({
		beforeToolCall({ toolName }) {
			if (toolName !== "agent") return undefined;
			return {
				block: true,
				additionalContext:
					"The built-in agent tool is disabled for this run because it runs outside the Pi host. Use the MCP tool '${tool}' to delegate; it keeps the subagent visible to the host. Do not retry agent.",
			};
		},
	});
}
`;
	const file = path.join(dir, STEERING_MOD_FILE);
	writeFileSync(file, source, { mode: 0o600 });
	return file;
}
